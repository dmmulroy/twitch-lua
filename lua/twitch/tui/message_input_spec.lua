local t = require("spec_helper")
local message_input = require("twitch.tui.message_input")

local function input_with(text)
	local input = message_input.new_message_input()
	input:insert_text(text)
	return input
end

t.test("message_input: insert at the cursor, backspace and delete", function()
	local input = input_with("helo")
	input:move_cursor(-1)
	input:insert_text("l")
	t.equal(input:text(), "hello")
	t.equal(input:delete_before_cursor(), true)
	t.equal(input:text(), "helo")
	t.equal(input:delete_at_cursor(), true)
	t.equal(input:text(), "hel")
	t.equal(input:delete_at_cursor(), false)
	input:move_cursor_to_start()
	t.equal(input:delete_before_cursor(), false)
end)

t.test("message_input: an emoji sequence is one step for the cursor and one backspace", function()
	local family = "👨" .. string.char(0xE2, 0x80, 0x8D) .. "👩"
	local input = input_with("a" .. family .. "b")
	input:move_cursor(-1)
	input:delete_before_cursor()
	t.equal(input:text(), "ab")
end)

t.test("message_input: control characters never enter the line", function()
	local input = input_with("a" .. string.char(27) .. "[31mb\nc")
	t.equal(input:text(), "a[31mb c")
end)

t.test("message_input: the character limit drops the overflow", function()
	local input = message_input.new_message_input({ max_characters = 5 })
	t.equal(input:insert_text("abcdefgh"), true)
	t.equal(input:text(), "abcde")
	t.equal(input:insert_text("x"), false)
end)

t.test("message_input: word movement and word, line-start and line-end deletes", function()
	local input = input_with("one two  three")
	input:move_cursor_word_left()
	input:insert_text("X")
	t.equal(input:text(), "one two  Xthree")
	input:move_cursor_word_left()
	input:move_cursor_word_left()
	input:move_cursor_word_right()
	input:insert_text("!")
	t.equal(input:text(), "one two!  Xthree")
	input:move_cursor_to_end()
	t.equal(input:delete_word_before_cursor(), true)
	t.equal(input:text(), "one two!  ")
	t.equal(input:delete_word_before_cursor(), true)
	t.equal(input:text(), "one ")
	input:insert_text("a b c")
	input:move_cursor(-2)
	t.equal(input:delete_to_line_end(), true)
	t.equal(input:text(), "one a b")
	t.equal(input:delete_to_line_start(), true)
	t.equal(input:text(), "")
	t.equal(input:delete_to_line_start(), false)
end)

t.test("message_input: take_message trims, clears and refuses a blank line", function()
	local input = input_with("  hello there  ")
	t.equal(input:take_message(), "hello there")
	t.equal(input:is_empty(), true)
	input:insert_text("   ")
	t.equal(input:take_message(), nil)
	t.equal(input:is_empty(), true)
end)

t.test("message_input: history goes back and forward and returns to the unsent line", function()
	local input = message_input.new_message_input()
	input:insert_text("first")
	input:take_message()
	input:insert_text("second")
	input:take_message()
	input:insert_text("draft")
	t.equal(input:browse_history(1), false)
	t.equal(input:browse_history(-1), true)
	t.equal(input:text(), "second")
	input:browse_history(-1)
	t.equal(input:text(), "first")
	t.equal(input:browse_history(-1), false)
	input:browse_history(1)
	t.equal(input:text(), "second")
	input:browse_history(1)
	t.equal(input:text(), "draft")
	-- sending the same message twice in a row is stored once
	input:take_message()
	input:insert_text("second")
	input:take_message()
	input:insert_text("second")
	input:take_message()
	input:browse_history(-1)
	input:browse_history(-1)
	t.equal(input:text(), "draft")
end)

t.test("message_input: restore_message puts a failed message back", function()
	local input = message_input.new_message_input()
	input:restore_message("try again")
	t.equal(input:text(), "try again")
	input:insert_text("!")
	t.equal(input:text(), "try again!")
end)

t.test("message_input: the visible window scrolls to keep the cursor in view", function()
	local input = input_with("0123456789")
	t.equal({ input:visible_window(20) }, { "0123456789", 10 })
	t.equal({ input:visible_window(5) }, { "6789", 4 })
	input:move_cursor_to_start()
	t.equal({ input:visible_window(5) }, { "01234", 0 })
	input:move_cursor(7)
	t.equal({ input:visible_window(5) }, { "34567", 4 })
	t.equal({ input:visible_window(0) }, { "", 0 })
	local wide = input_with("日本語日本語")
	t.equal({ wide:visible_window(5) }, { "本語", 4 })
end)
