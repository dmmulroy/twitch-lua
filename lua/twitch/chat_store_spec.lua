local t = require("spec_helper")
local chat_store = require("twitch.chat_store")

local function message(seq, id, user_id, text)
	return { seq = seq, kind = "message", id = id, user_id = user_id, name = "u" .. user_id, text = text }
end

t.test("chat_store: keeps messages in order and gives each an entry id", function()
	local store = chat_store.new_chat_store()
	t.equal(store:apply_chat_event(message(1, "a", "1", "one")), true)
	t.equal(store:apply_chat_event(message(2, "b", "2", "two")), true)
	t.equal(#store.entries, 2)
	t.equal(store.entries[1].text, "one")
	t.truthy(store.entries[1].entry_id ~= store.entries[2].entry_id)
	t.equal(store.revision, 2)
end)

t.test("chat_store: a replayed sequence number or a repeated message id changes nothing", function()
	local store = chat_store.new_chat_store()
	store:apply_chat_event(message(5, "a", "1", "one"))
	t.equal(store:apply_chat_event(message(5, "a", "1", "one")), false)
	t.equal(store:apply_chat_event(message(3, "z", "1", "older")), false)
	t.equal(store:apply_chat_event(message(6, "a", "1", "same twitch message again")), false)
	t.equal(#store.entries, 1)
end)

t.test("chat_store: delete marks one message; clear_user marks that person's messages", function()
	local store = chat_store.new_chat_store()
	store:apply_chat_event(message(1, "a", "1", "one"))
	store:apply_chat_event(message(2, "b", "2", "two"))
	store:apply_chat_event(message(3, "c", "1", "three"))
	t.equal(store:apply_chat_event({ seq = 4, kind = "delete", message_id = "b" }), true)
	t.equal(store.entries[2].deleted, true)
	t.equal(store:apply_chat_event({ seq = 5, kind = "delete", message_id = "b" }), false)
	t.equal(store:apply_chat_event({ seq = 6, kind = "delete", message_id = "nope" }), false)
	t.equal(store:apply_chat_event({ seq = 7, kind = "clear_user", user_id = "1" }), true)
	t.equal(store.entries[1].deleted, true)
	t.equal(store.entries[3].deleted, true)
	t.equal(store:apply_chat_event({ seq = 8, kind = "clear_user", user_id = "1" }), false)
end)

t.test("chat_store: clear empties the chat and says so", function()
	local store = chat_store.new_chat_store()
	store:apply_chat_event(message(1, "a", "1", "one"))
	store:apply_chat_event({ seq = 2, kind = "clear" })
	t.equal(#store.entries, 1)
	t.equal(store.entries[1].kind, "status")
	-- the cleared message id can be used again
	t.equal(store:apply_chat_event(message(3, "a", "1", "one again")), true)
end)

t.test("chat_store: consecutive status lines collapse into the latest one", function()
	local store = chat_store.new_chat_store()
	store:apply_chat_event({ seq = 1, kind = "status", level = "info", text = "Connecting to Twitch", state = "connecting" })
	t.equal(store.connection_state, "connecting")
	store:apply_chat_event({ seq = 2, kind = "status", level = "warn", text = "retry in 1s", state = "reconnecting" })
	store:apply_chat_event({ seq = 3, kind = "status", level = "warn", text = "retry in 2s", state = "reconnecting" })
	t.equal(#store.entries, 1)
	t.equal(store.entries[1].text, "retry in 2s")
	t.equal(store:apply_chat_event({ seq = 4, kind = "status", level = "warn", text = "retry in 2s", state = "reconnecting" }), false)
	store:apply_chat_event(message(5, "a", "1", "hi"))
	store:apply_chat_event({ seq = 6, kind = "status", level = "info", text = "Joined chat", state = "joined" })
	t.equal(#store.entries, 3)
	t.equal(store.connection_state, "joined")
end)

t.test("chat_store: the oldest entries are dropped past the limit", function()
	local store = chat_store.new_chat_store({ max_entries = 3 })
	for i = 1, 5 do
		store:apply_chat_event(message(i, "m" .. i, "1", "text " .. i))
	end
	t.equal(#store.entries, 3)
	t.equal(store.entries[1].text, "text 3")
	-- a dropped message can no longer be deleted
	t.equal(store:apply_chat_event({ seq = 9, kind = "delete", message_id = "m1" }), false)
end)

t.test("chat_store: unknown kinds and junk are ignored", function()
	local store = chat_store.new_chat_store()
	t.equal(store:apply_chat_event({ seq = 1, kind = "emote_ready" }), false)
	t.equal(store:apply_chat_event(nil), false)
	t.equal(store.last_seq, 1)
end)
