#!/bin/sh
# Writes rockspecs/twitch-lua-<version>-1.rockspec: every module under lua/twitch/ except
# the specs. Run it again whenever a module is added or removed, and for each release.
#
#   scripts/write_rockspec.sh <version> [distilled-lua version]
#   scripts/write_rockspec.sh 0.1.0
#
# The rock builds from the git tag v<version>. Its dependencies are distilled-lua's runtime
# (rock `distilled`) and generated Twitch client (rock `distilled-twitch`, modules
# distilled.clients.twitch.*), which replace vendor/ when twitch-lua is installed as a rock.
# Try it from a checkout without publishing (distilled-lua's scripts/build_rocks.sh
# writes the local server):
#   luarocks --lua-version 5.1 --tree /tmp/rocks \
#     --only-server "file://$HOME/Code/personal/distilled-lua/dist/rocks/0.1.0" \
#     make rockspecs/twitch-lua-0.1.0-1.rockspec
set -eu

if [ $# -lt 1 ]; then
  echo "usage: scripts/write_rockspec.sh <version> [distilled-lua version]" >&2
  exit 2
fi
version="$1"
distilled_version="${2:-0.1.0}"
repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/rockspecs/twitch-lua-$version-1.rockspec"
mkdir -p "$repo/rockspecs"

modules="$(cd "$repo" && find lua/twitch -type f -name '*.lua' ! -name '*_spec.lua' | LC_ALL=C sort |
  awk '{ module = $0; sub(/^lua\//, "", module); sub(/\.lua$/, "", module); sub(/\/init$/, "", module); gsub(/\//, ".", module);
         printf "    [\"%s\"] = \"%s\",\n", module, $0 }')"

cat > "$out" <<ROCKSPEC
-- Generated by scripts/write_rockspec.sh. Do not edit.
rockspec_format = "3.0"
package = "twitch-lua"
version = "$version-1"
source = {
  url = "git+https://github.com/dmmulroy/twitch-lua.git",
  tag = "v$version",
}
description = {
  summary = "Twitch chat in a Rex pane, written in Lua",
  detailed = "One process holds the only EventSub connection and every tab's chat pane reads from it. Looks like twitch-tui (twt), with emote images (animated ones too), clickable links, moderation commands and Rex palette actions.",
  homepage = "https://github.com/dmmulroy/twitch-lua",
  license = "Apache-2.0",
  labels = { "twitch", "chat", "rex", "terminal" },
}
dependencies = {
  "lua >= 5.1",
  "distilled == $distilled_version",
  "distilled-twitch == $distilled_version",
}
build = {
  type = "builtin",
  modules = {
$modules
  },
}
ROCKSPEC
echo "wrote $out ($(printf '%s\n' "$modules" | wc -l | tr -d ' ') modules)"
