#!/bin/sh
# Rebuilds lua/twitch/top_level_domains.lua from IANA's list of every top-level domain
# (https://data.iana.org/TLD/tlds-alpha-by-domain.txt). Bare links in chat
# (twitch.chat_links) are linked when their last label is one of these.
#
#   scripts/generate_top_level_domains.sh [path to a downloaded tlds-alpha-by-domain.txt]
set -eu
repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/lua/twitch/top_level_domains.lua"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
if [ $# -ge 1 ]; then
  cp "$1" "$work/tlds.txt"
else
  curl -fsSL https://data.iana.org/TLD/tlds-alpha-by-domain.txt -o "$work/tlds.txt"
fi
version="$(head -1 "$work/tlds.txt" | sed 's/^# *//')"
{
  echo "-- Every top-level domain in IANA's root zone, lowercase: TOP_LEVEL_DOMAINS[\"tv\"] == true."
  echo "-- Generated by scripts/generate_top_level_domains.sh; do not edit."
  echo "-- IANA tlds-alpha-by-domain.txt, $version"
  echo "return {"
  grep -v '^#' "$work/tlds.txt" | grep -E '^[A-Z0-9-]+$' | tr 'A-Z' 'a-z' | sed 's/^\(.*\)$/\t["\1"] = true,/'
  echo "}"
} > "$out"
echo "wrote $out ($(grep -c '= true' "$out") domains)"
